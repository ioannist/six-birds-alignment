#!/usr/bin/env python3
"""Generate figures/argument_map.tex (the argument map, Figure 3) from figures/argument_map.yaml.

Usage (from paper/):  python3 figures/make_argument_map.py [yaml] [out.tex]
"""
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / "argument_map.yaml"
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else HERE / "argument_map.tex"

STYLES = r"""
  font=\footnotesize,
  execute at begin node={\hyphenpenalty=10000\exhyphenpenalty=10000},
  premise/.style={draw, dashed, rounded corners=1pt, align=center, text width=2.7cm, minimum height=0.8cm, inner sep=2pt},
  conjunction/.style={circle, fill=black, inner sep=0pt, minimum size=4pt},
  thesis/.style={draw, very thick, fill=white, align=center, text width=2.5cm, minimum height=1.0cm, font=\footnotesize\bfseries},
  family/.style={draw, align=center, text width=3.4cm, minimum height=0.75cm, inner sep=2pt},
  failed/.style={align=center, text width=3.0cm, text=red!75!black, font=\scriptsize},
  argument/.style={draw, double, double distance=1.2pt, align=center, text width=3.3cm, minimum height=0.75cm, inner sep=2pt},
  argument_cs/.style={argument},
  bridge/.style={draw, double, double distance=1pt, align=center, text width=3.35cm, inner sep=1.5pt, font=\scriptsize\itshape},
  boundary/.style={draw, densely dotted, thick, align=center, text width=3.4cm, minimum height=0.6cm, inner sep=2pt, font=\scriptsize},
  qualification/.style={draw, dash dot dot, thick, align=center, text width=3.7cm, minimum height=0.6cm, inner sep=2pt, font=\scriptsize},
  covenant/.style={draw, fill=black!12, align=center, text width=2.9cm, minimum height=0.8cm, inner sep=2pt},
  rel member/.style={draw, thin},
  rel inf/.style={draw, thick, -{Stealth[length=2.2mm]}},
  rel sup/.style={draw, thick, black!55, -{Stealth[open, length=2.2mm]}},
  rel mot/.style={draw, densely dotted, thick, -{Stealth[length=2mm]}},
  rel constrains/.style={draw, semithick, red!75!black, densely dashed},
"""


def esc(label: str) -> str:
    return label.replace("&", r"\&").replace("%", r"\%")


def node_text(n):
    txt = esc(n["label"])
    if n.get("note"):
        txt += r"\\[-1pt]{\scriptsize\itshape " + esc(n["note"]) + "}"
    for t in n.get("tags", []):
        txt += r"\\[-1pt]{\scriptsize\itshape " + esc(t) + "}"
    return txt


def main():
    data = yaml.safe_load(SRC.read_text(encoding="utf-8"))
    nodes = {n["id"]: n for n in data["nodes"]}
    out = [
        "% Generated by figures/make_argument_map.py from figures/argument_map.yaml; do not edit by hand.",
        r"\begin{tikzpicture}[",
        STYLES.strip("\n"),
        "]",
    ]
    band = data.get("band")
    if band:
        out.append(f"  \\fill[black!5, rounded corners=3pt] ({band['x0']},{band['y0']}) rectangle ({band['x1']},{band['y1']});")
    slot_y = {}
    for n in data["nodes"]:
        ss = n.get("sup_slots") or []
        for i, src in enumerate(ss):
            slot_y[(src, n["id"])] = 0.36 - 0.72 * i / max(len(ss) - 1, 1)
    for n in data["nodes"]:
        x, y = n["pos"]
        out.append(f"  \\node[{n['kind']}] ({n['id']}) at ({x},{y}) {{{node_text(n)}}};")
        if n.get("bridge"):
            out.append(f"  \\node[bridge, anchor=north] ({n['id']}_bridge) at ([yshift=-1.5pt]{n['id']}.south) "
                       "{" + (esc(n['bridge']) if n['bridge'] == "stated bridge" else "bridge: " + esc(n['bridge'])) + "};")
    out.append("  % relations")
    drawn_group = {}
    for r in data["relations"]:
        a, b, t = r["from"], r["to"], r["type"]
        if t == "member":
            out.append(f"  \\path[rel member] ({a}.east) -- ({b});")
        elif t == "inf":
            out.append(f"  \\path[rel inf] ({a}) -- ({b}.west);")
        elif t == "sup" and "via_x" in r:
            dy = slot_y.get((a, b), 0)
            ly = nodes[a]["pos"][1] + 0.2
            if "via_y" in r:
                out.append(f"  \\path[rel sup] ([yshift=2mm]{a}.west) -- ({r['via_x']},{ly:.2f}) -- ({r['via_x']},{r['via_y']}) "
                           f"-| ([xshift=0.8cm]{b}.south);")
            else:
                out.append(f"  \\path[rel sup] ([yshift=2mm]{a}.west) -- ({r['via_x']},{ly:.2f}) "
                           f"|- ([yshift={dy:.2f}cm]{b}.east);")
        elif t == "sup":
            dy = slot_y.get((a, b), 0)
            src = f"[yshift=-1.5mm]{a}.west" if any(rr.get("from") == a and "via_x" in rr for rr in data["relations"]) else f"{a}.west"
            out.append(f"  \\path[rel sup] ({src}) -- ([yshift={dy:.2f}cm]{b}.east);")
        elif t == "constrains":
            out.append(f"  \\path[rel constrains] ({a}.west) -- ({b}.east);")
        elif t == "mot" and "route" in r and "route_y" in r:
            x, yy = r["route"][0], r["route_y"]
            out.append(f"  \\path[rel mot] ({a}.west) -- ({x},0 |- {a}.west) -- ({x},{yy}) -| ({b}.south);")
            if r.get("label"):
                lx, ly = r["label_pos"]
                out.append(f"  \\node[font=\\scriptsize\\itshape, align=center, text width=3.0cm, inner sep=1pt] "
                           f"at ({lx},{ly}) {{{esc(r['label'])}}};")
        elif t == "mot" and r.get("group") == "theses":
            if not band:
                raise SystemExit("group: theses needs a `band`")
            srcs = {rr["from"] for rr in data["relations"] if rr.get("group") == "theses" and rr["to"] == b}
            if srcs != {n["id"] for n in data["nodes"] if n["kind"] == "thesis"}:
                raise SystemExit(f"group theses -> {b}: sources {sorted(srcs)} are not all the theses; 'each thesis' would be false")
            if not drawn_group.get(b):
                drawn_group[b] = True
                out.append(f"  \\path[rel mot] ({nodes[b]['pos'][0]},{band['y0']}) -- ({b}.north)"
                           f" node[midway, right, font=\\scriptsize\\itshape, inner sep=2pt] {{{esc(band['label'])}}};")
        elif t == "mot":
            out.append(f"  \\path[rel mot] ({a}) -- ({b});")
        else:
            raise SystemExit(f"unknown relation type {t!r}")
    out += [
        "  % legend",
        r"  \begin{scope}[shift={(0.1,-1.9)}, font=\scriptsize]",
        r"    \draw[thick, -{Stealth[length=2mm]}] (0,0) -- (0.7,0) node[right, black] {inference};",
        r"    \draw[thick, black!55, -{Stealth[open, length=2mm]}] (0,-0.32) -- (0.7,-0.32) node[right, black] {scoped support};",
        r"    \draw[densely dotted, thick, -{Stealth[length=2mm]}] (0,-0.64) -- (0.7,-0.64) node[right] {motivation};",
        r"    \draw[red!75!black, densely dashed] (0,-0.96) -- (0.7,-0.96) node[right, text=red!75!black] {failed inference ($\nRightarrow$)};",
        r"  \end{scope}",
        r"  \begin{scope}[shift={(3.7,-1.9)}, font=\scriptsize]",
        r"    \draw (0.1,-0.1) rectangle (0.6,0.1); \node[right] at (0.7,0) {established result};",
        r"    \draw[dashed] (0.1,-0.42) rectangle (0.6,-0.22); \node[right] at (0.7,-0.32) {assumed premise};",
        r"    \draw[double, double distance=1pt] (0.1,-0.74) rectangle (0.6,-0.54); \node[right] at (0.7,-0.64) {argument or bridge};",
        r"    \draw[densely dotted, thick] (0.1,-1.06) rectangle (0.6,-0.86); \node[right] at (0.7,-0.96) {open boundary};",
        r"    \draw[fill=black!12] (0.1,-1.38) rectangle (0.6,-1.18); \node[right] at (0.7,-1.28) {charter};",
        r"    \draw[dash dot dot, thick] (0.1,-1.70) rectangle (0.6,-1.50); \node[right, text width=3.5cm, align=left, anchor=north west] at (0.7,-1.44) {unproved obligation; assumed postulate};",
        r"  \end{scope}",
        r"  \ifshowstubs\node[font=\scriptsize\itshape, text=black!45, anchor=north east] at (16.0,15.3) {scaffold layout (A8)};\fi",
        r"\end{tikzpicture}",
    ]
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(nodes)} nodes, {len(data['relations'])} relations)")


if __name__ == "__main__":
    main()
